def resolve_city(name: str) -> str:
    """城市名 → Boss 城市码；未知城市抛出带修复提示的 KeyError。"""
    name = name.strip()
    if name in BOSS_CITY_CODES:
        return BOSS_CITY_CODES[name]
    raise KeyError(
        f"Boss 城市码表中没有「{name}」，请在 backend/utils/city_codes.py 的 BOSS_CITY_CODES 中补充"
    )
